"""Regenerates src/routeTree.gen.ts for flat file routes when the Vite plugin
cannot run (the TanStack Router plugin overwrites this file on every build)."""
import os
ROOT = os.path.join(os.path.dirname(__file__), "..")
R = os.path.join(ROOT, "src", "routes")
routes = sorted(f[:-4] for f in os.listdir(R) if f.endswith(".tsx") and f not in ("__root.tsx", "index.tsx"))
ident = lambda n: "".join(w.capitalize() for w in n.split("-")) + "Route"
imports = ["import { Route as rootRouteImport } from './routes/__root'"] + [f"import {{ Route as {ident(r)}Import }} from './routes/{r}'" for r in routes] + ["import { Route as IndexRouteImport } from './routes/index'"]
defs = [f"const {ident(r)} = {ident(r)}Import.update({{\n  id: '/{r}',\n  path: '/{r}',\n  getParentRoute: () => rootRouteImport,\n}} as any)" for r in routes]
defs.append("const IndexRoute = IndexRouteImport.update({\n  id: '/',\n  path: '/',\n  getParentRoute: () => rootRouteImport,\n} as any)")
allr = [("/", "IndexRoute", "IndexRouteImport")] + [(f"/{r}", ident(r), ident(r) + "Import") for r in routes]
by = "\n".join(f"  '{p}': typeof {i}" for p, i, _ in allr)
paths = " | ".join(f"'{p}'" for p, _, _ in allr)
nl = "\n"
decl = nl.join(f"    '{p}': {{{nl}      id: '{p}'{nl}      path: '{p}'{nl}      fullPath: '{p}'{nl}      preLoaderRoute: typeof {imp}{nl}      parentRoute: typeof rootRouteImport{nl}    }}" for p, _, imp in allr)
out = f"""/* eslint-disable */

// @ts-nocheck

// noinspection JSUnusedGlobalSymbols

// This file was automatically generated by TanStack Router.
// You should NOT make any changes in this file as it will be overwritten.
// Additionally, you should also exclude this file from your linter and/or formatter to prevent it from being checked or modified.

{nl.join(imports)}

{nl.join(defs)}

export interface FileRoutesByFullPath {{
{by}
}}
export interface FileRoutesByTo {{
{by}
}}
export interface FileRoutesById {{
  __root__: typeof rootRouteImport
{by}
}}
export interface FileRouteTypes {{
  fileRoutesByFullPath: FileRoutesByFullPath
  fullPaths: {paths}
  fileRoutesByTo: FileRoutesByTo
  to: {paths}
  id: '__root__' | {paths}
  fileRoutesById: FileRoutesById
}}
export interface RootRouteChildren {{
{nl.join(f"  {i}: typeof {i}" for _, i, _ in allr)}
}}

declare module '@tanstack/react-router' {{
  interface FileRoutesByPath {{
{decl}
  }}
}}

const rootRouteChildren: RootRouteChildren = {{
{nl.join(f"  {i}: {i}," for _, i, _ in allr)}
}}
export const routeTree = rootRouteImport
  ._addFileChildren(rootRouteChildren)
  ._addFileTypes<FileRouteTypes>()

import type {{ getRouter }} from './router.tsx'
import type {{ startInstance }} from './start.ts'
declare module '@tanstack/react-start' {{
  interface Register {{
    ssr: true
    router: Awaited<ReturnType<typeof getRouter>>
    config: Awaited<ReturnType<typeof startInstance.getOptions>>
  }}
}}
"""
open(os.path.join(ROOT, "src", "routeTree.gen.ts"), "w").write(out)
print(len(allr), "routes")
